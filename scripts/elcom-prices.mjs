#!/usr/bin/env node
// Saves ElCom's 2027 household tariffs (H4, standard product, total) for every municipality of
// Basel-Stadt and Bern to packages/economics/src/prices.json, with the Swiss median, so the map's
// card has a price without the network. A few kB; run it again when ElCom publishes new tariffs.
//   node scripts/elcom-prices.mjs
import { writeFileSync } from "node:fs";
import {
  ELCOM_GRAPHQL,
  TARIFF,
  byMunicipality,
  observationsQuery,
  parseObservations,
  parseSwissMedian,
  swissMedianQuery,
} from "../packages/economics/src/elcom.ts";

export const OUT = "packages/economics/src/prices.json";

/** BFS numbers: Basel-Stadt is 2701 to 2703, Bern's municipalities lie in 301 to 999. */
const CANTONS = {
  BS: [2701, 2702, 2703],
  BE: Array.from({ length: 699 }, (_, i) => 301 + i),
};

/** Municipalities per request: ElCom times out on long lists. */
const CHUNK = 20;

async function ask(query, tries = 4) {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(ELCOM_GRAPHQL, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ query }),
      });
      if (res.ok) return await res.json();
      throw new Error(`HTTP ${res.status}`);
    } catch (err) {
      if (i >= tries) throw err;
      await new Promise((r) => setTimeout(r, 2000 * i));
    }
  }
}

async function main() {
  const municipalities = {};
  for (const [canton, ids] of Object.entries(CANTONS)) {
    for (let at = 0; at < ids.length; at += CHUNK) {
      const query = observationsQuery(ids.slice(at, at + CHUNK));
      // Large or unlucky requests sometimes come back empty: ask an empty chunk once more.
      let obs = parseObservations(await ask(query));
      if (obs.length === 0) obs = parseObservations(await ask(query));
      for (const [id, m] of Object.entries(byMunicipality(obs))) {
        municipalities[id] = { canton, ...m, rpPerKwh: Number(m.rpPerKwh.toFixed(3)) };
      }
    }
  }
  const swiss = parseSwissMedian(await ask(swissMedianQuery()));
  if (swiss === null || Object.keys(municipalities).length < 3) {
    throw new Error("ElCom gave no answer; prices.json is unchanged.");
  }
  const data = {
    _note: "Generated by scripts/elcom-prices.mjs from ElCom's API. Do not edit.",
    source: `ElCom, strompreis.elcom.admin.ch, ${TARIFF.period} ${TARIFF.category} ${TARIFF.product} product, total without VAT`,
    fetched: new Date().toISOString().slice(0, 10),
    ...TARIFF,
    swissMedianRpPerKwh: swiss,
    municipalities,
  };
  writeFileSync(OUT, JSON.stringify(data, null, 2) + "\n");
  console.log(
    `${OUT}: ${Object.keys(municipalities).length} municipalities, Swiss median ${swiss}`,
  );
}

await main();
